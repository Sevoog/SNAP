// Captures a snapshot of the current network state (interfaces, external IP,
// gateway, DNS, recent alerts) and writes a self-contained HTML report. The
// report is intentionally a single file with inline CSS so it can be emailed
// or attached to a ticket without external assets.

import Foundation
import AppKit
import Darwin

@MainActor
enum SessionReporter {

    static func writeReport() {
        let panel = NSSavePanel()
        panel.title = "Save Session Report"
        panel.allowedContentTypes = [.html]
        let stamp = stamp()
        panel.nameFieldStringValue = "SNAP_Session_\(stamp).html"
        panel.canCreateDirectories = true
        panel.begin { resp in
            guard resp == .OK, let url = panel.url else { return }
            Task {
                let html = await build()
                try? html.write(to: url, atomically: true, encoding: .utf8)
                NSWorkspace.shared.open(url)
            }
        }
    }

    private static func stamp() -> String {
        let fmt = DateFormatter()
        fmt.dateFormat = "yyyyMMdd_HHmmss"
        return fmt.string(from: Date())
    }

    // MARK: Build

    static func build() async -> String {
        let provider = NetworkInfoProvider()
        provider.refresh()
        // Wait a tick for external IP fetch
        try? await Task.sleep(nanoseconds: 600_000_000)
        let interfaces = provider.interfaces
        let externalIP = provider.externalIP

        let gateway = await defaultGateway()
        let dns = await systemDNS()
        let alerts = AlertManager.shared.recentEvents

        let host = ProcessInfo.processInfo.hostName
        let os   = ProcessInfo.processInfo.operatingSystemVersionString
        let now  = Date().formatted(date: .complete, time: .complete)

        var html = ""
        html.append(header)

        html.append("<header><h1>SNAP Session Report</h1>")
        html.append("<p class='meta'>\(escape(now)) · \(escape(host)) · \(escape(os))</p></header>")

        html.append(section(title: "Snapshot") {
            kvTable([
                ("Hostname",        host),
                ("External IP",     externalIP),
                ("Default Gateway", gateway ?? "—"),
                ("System DNS",      dns.isEmpty ? "—" : dns.joined(separator: ", ")),
                ("Generated by",    "SNAP — Sev's Network Analysis Platform v\(AppInfo.version)"),
            ])
        })

        html.append(section(title: "Interfaces (\(interfaces.count))") {
            var s = "<table class='wide'><thead><tr><th>Name</th><th>Friendly</th><th>IPv4</th><th>IPv6</th><th>Status</th></tr></thead><tbody>"
            for i in interfaces {
                s += "<tr>"
                s += "<td><code>\(escape(i.name))</code></td>"
                s += "<td>\(escape(i.displayName))</td>"
                s += "<td><code>\(escape(i.ipv4.joined(separator: ", ")))</code></td>"
                s += "<td><code>\(escape(i.ipv6.joined(separator: ", ")))</code></td>"
                s += "<td>\(i.isUp ? "<span class='up'>UP</span>" : "<span class='down'>DOWN</span>")</td>"
                s += "</tr>"
            }
            s += "</tbody></table>"
            return s
        })

        html.append(section(title: "Recent Alerts (\(alerts.count))") {
            if alerts.isEmpty {
                return "<p class='muted'>No threshold alerts have fired this session.</p>"
            }
            var s = "<table class='wide'><thead><tr><th>Time</th><th>Metric</th><th>Value</th><th>Message</th></tr></thead><tbody>"
            for ev in alerts.prefix(20) {
                s += "<tr>"
                s += "<td><code>\(escape(ev.date.formatted(date: .omitted, time: .standard)))</code></td>"
                s += "<td>\(escape(ev.metric.label))</td>"
                s += "<td><code>\(String(format: "%.1f", ev.value)) \(ev.metric.unit)</code></td>"
                s += "<td>\(escape(ev.body))</td>"
                s += "</tr>"
            }
            s += "</tbody></table>"
            return s
        })

        html.append(section(title: "Notes") {
            "<textarea rows='8' placeholder='Add observations, repro steps, or context for this report. Notes are saved with the HTML when you print or save the page.'></textarea>"
        })

        html.append(footer)
        return html
    }

    // MARK: HTML scaffolding

    private static func section(title: String, _ body: () -> String) -> String {
        "<section><h2>\(escape(title))</h2>\(body())</section>"
    }

    private static func kvTable(_ pairs: [(String, String)]) -> String {
        var s = "<table class='kv'>"
        for (k, v) in pairs {
            s += "<tr><th>\(escape(k))</th><td><code>\(escape(v))</code></td></tr>"
        }
        s += "</table>"
        return s
    }

    private static func escape(_ s: String) -> String {
        s.replacingOccurrences(of: "&", with: "&amp;")
         .replacingOccurrences(of: "<", with: "&lt;")
         .replacingOccurrences(of: ">", with: "&gt;")
    }

    // MARK: System inspection

    private static func defaultGateway() async -> String? {
        RouteInfo.defaultGateway()
    }

    private static func systemDNS() async -> [String] {
        // SCDynamicStore's global DNS ServerAddresses — the effective
        // resolvers, without parsing `scutil --dns`.
        DNSInfo.systemResolvers().sorted()
    }

    // MARK: Inline styles

    private static let header = """
    <!doctype html>
    <html lang="en">
    <head>
    <meta charset="utf-8">
    <title>SNAP Session Report</title>
    <style>
      :root {
        --bg: #0a0a0f;
        --bg2: #11111a;
        --text1: #f1f1f5;
        --text2: #aaaab0;
        --text3: #65656e;
        --amber: #ff9500;
        --green: #30d158;
        --red:   #ff3b30;
        --border: rgba(255,255,255,0.07);
      }
      * { box-sizing: border-box; }
      body {
        margin: 0; padding: 0;
        font: 14px/1.5 -apple-system, BlinkMacSystemFont, "SF Pro Text", "Helvetica Neue", sans-serif;
        background: var(--bg); color: var(--text1);
      }
      header {
        padding: 28px 32px; border-bottom: 1px solid var(--border);
      }
      header h1 {
        margin: 0; font-size: 22px; font-weight: 600;
        background: linear-gradient(90deg, var(--amber), #ffb74d);
        -webkit-background-clip: text; -webkit-text-fill-color: transparent;
      }
      header .meta { color: var(--text3); font-size: 12px; margin-top: 6px; font-family: ui-monospace, SFMono-Regular, monospace; }
      section { padding: 20px 32px; border-bottom: 1px solid var(--border); }
      section h2 { margin: 0 0 12px; font-size: 13px; font-weight: 600; text-transform: uppercase; letter-spacing: 0.5px; color: var(--text3); }
      code { font-family: ui-monospace, SFMono-Regular, monospace; font-size: 12px; color: var(--text2); }
      table { border-collapse: collapse; }
      table.kv { width: 100%; }
      table.kv th { text-align: left; color: var(--text3); padding: 4px 12px 4px 0; font-weight: 500; font-size: 12px; width: 180px; }
      table.kv td { padding: 4px 0; }
      table.wide { width: 100%; }
      table.wide th { text-align: left; color: var(--text3); padding: 8px 12px; font-weight: 500; font-size: 11px; text-transform: uppercase; letter-spacing: 0.5px; border-bottom: 1px solid var(--border); }
      table.wide td { padding: 8px 12px; border-bottom: 1px solid var(--border); font-size: 12px; }
      .up    { color: var(--green); font-weight: 600; font-size: 11px; }
      .down  { color: var(--text3); font-size: 11px; }
      .muted { color: var(--text3); font-size: 12px; }
      textarea {
        width: 100%; background: var(--bg2); color: var(--text1); border: 1px solid var(--border);
        border-radius: 6px; padding: 10px; font: inherit; font-size: 13px;
      }
      footer { padding: 20px 32px; color: var(--text3); font-size: 11px; }
    </style>
    </head>
    <body>
    """

    private static let footer = """
    <footer>SNAP — Sev's Network Analysis Platform · © 2025–2026 Sevag Bardakjian</footer>
    </body>
    </html>
    """
}

